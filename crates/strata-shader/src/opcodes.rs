/// Total number of GFX10.3 / RDNA2 opcodes in [`OPCODE_TABLE`].
pub const fn opcode_count() -> usize {
    OPCODE_TABLE.len()
}

/// Look up full [`OpcodeInfo`] by `(encoding, opcode)`.
pub fn lookup_opcode_info(encoding: Encoding, opcode: u16) -> Option<OpcodeInfo> {
    OPCODE_TABLE
        .iter()
        .copied()
        .find(|info| info.encoding == encoding && info.opcode == opcode)
}

/// GFX10.3 / RDNA2 opcode mnemonic lookup by `(encoding, opcode)`.
pub fn lookup_opcode(encoding: Encoding, opcode: u16) -> Option<&'static str> {
    lookup_opcode_info(encoding, opcode).map(|info| info.mnemonic)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn opcode_table_covers_400_plus_gfx10_3_opcodes_across_all_18_encodings() {
        assert!(
            opcode_count() >= 400,
            "expected 400+ opcodes, got {}",
            opcode_count()
        );
        let all_encodings = [
            Encoding::Sopp,
            Encoding::Sopc,
            Encoding::Sop1,
            Encoding::Sopk,
            Encoding::Sop2,
            Encoding::Smem,
            Encoding::Vop1,
            Encoding::Vopc,
            Encoding::Vop2,
            Encoding::Vop3,
            Encoding::Vop3p,
            Encoding::Vintrp,
            Encoding::Ds,
            Encoding::Mubuf,
            Encoding::Mtbuf,
            Encoding::Flat,
            Encoding::Mimg,
            Encoding::Exp,
        ];
        for enc in all_encodings {
            assert!(
                OPCODE_TABLE.iter().any(|info| info.encoding == enc),
                "encoding {enc:?} missing from OPCODE_TABLE"
            );
        }
    }

    #[test]
    fn opcode_table_resolves_bvh_cube_permutes_and_scratch() {
        assert_eq!(
            lookup_opcode(Encoding::Mimg, 0x65),
            Some("image_bvh_intersect_ray")
        );
        assert_eq!(
            lookup_opcode(Encoding::Mimg, 0x66),
            Some("image_bvh64_intersect_ray")
        );
        assert_eq!(lookup_opcode(Encoding::Vop3, 0x144), Some("v_cubeid_f32"));
        assert_eq!(
            lookup_opcode(Encoding::Vop3, 0x377),
            Some("v_permlane16_b32")
        );
        assert_eq!(lookup_opcode(Encoding::Ds, 0xb2), Some("ds_bpermute_b32"));
        assert_eq!(
            lookup_opcode(Encoding::Flat, 0x0c),
            Some("scratch_load_dword")
        );
        assert_eq!(lookup_opcode(Encoding::Vop3p, 0x0e), Some("v_pk_fma_f16"));
        assert_eq!(lookup_opcode(Encoding::Exp, 0), Some("exp"));
    }
}
