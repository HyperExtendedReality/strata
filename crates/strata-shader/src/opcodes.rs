#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn opcode_table_resolves_bvh_cube_permutes_and_scratch() {
        assert_eq!(
            lookup_opcode(Encoding::Mimg, 0x65),
            Some("image_bvh_intersect_ray")
        );
        assert_eq!(
            lookup_opcode(Encoding::Mimg, 0x66),
            Some("image_bvh64_intersect_ray")
        );
        assert_eq!(lookup_opcode(Encoding::Vop3, 0x144), Some("v_cubeid_f32"));
        assert_eq!(
            lookup_opcode(Encoding::Vop3, 0x377),
            Some("v_permlane16_b32")
        );
        assert_eq!(lookup_opcode(Encoding::Ds, 0xb2), Some("ds_bpermute_b32"));
        assert_eq!(
            lookup_opcode(Encoding::Flat, 0x0c),
            Some("scratch_load_dword")
        );
        assert_eq!(lookup_opcode(Encoding::Vop3p, 0x0e), Some("v_pk_fma_f16"));
    }
}
