"""Generate crates/strata-shader/src/opcodes.rs from AMD's machine-readable RDNA2 ISA.

Input, either:
  * amdgpu_isa_rdna2.xml from https://gpuopen.com/machine-readable-isa/ (MIT licence), or
  * xcl's crates/xcl/src/gpu/rdna2_spec.rs, which xcl generates from that same XML
    (xcl, GPL-3.0-or-later, https://github.com/ -- see THIRD_PARTY_NOTICES.md).

Only (encoding, opcode, mnemonic, size) is taken: the instruction identities the
hardware defines. Strata's decoding rules stay its own.

Usage:
    python -I scripts/gen_isa_table.py <xml-or-rdna2_spec.rs> crates/strata-shader/src/opcodes.rs
"""

import re
import sys
import xml.etree.ElementTree as ET

# AMD encoding name -> (Strata `Encoding` variant, dwords without literal)
ENC = {
    "ENC_SOPP": ("Sopp", 1),
    "ENC_SOPC": ("Sopc", 1),
    "ENC_SOP1": ("Sop1", 1),
    "ENC_SOPK": ("Sopk", 1),
    "ENC_SOP2": ("Sop2", 1),
    "ENC_SMEM": ("Smem", 2),
    "ENC_VOP1": ("Vop1", 1),
    "ENC_VOPC": ("Vopc", 1),
    "ENC_VOP2": ("Vop2", 1),
    "ENC_VOP3": ("Vop3", 2),
    "VOP3_SDST_ENC": ("Vop3", 2),
    "ENC_VOP3P": ("Vop3p", 2),
    "ENC_VINTRP": ("Vintrp", 1),
    "ENC_DS": ("Ds", 2),
    "ENC_MUBUF": ("Mubuf", 2),
    "ENC_MTBUF": ("Mtbuf", 2),
    "ENC_FLAT": ("Flat", 2),
    "ENC_FLAT_GLBL": ("FlatGlobal", 2),
    "ENC_FLAT_SCRATCH": ("FlatScratch", 2),
    "ENC_MIMG": ("Mimg", 2),
    "ENC_EXP": ("Exp", 2),
}


def from_xml(path):
    root = ET.parse(path).getroot()
    isa = root.find("ISA")
    out = []
    for ins in isa.find("Instructions"):
        name = ins.findtext("InstructionName")
        for enc in ins.find("InstructionEncodings"):
            if enc.findtext("EncodingCondition", "default") != "default":
                continue
            out.append((enc.findtext("EncodingName"), int(enc.findtext("Opcode")), name))
    return out


def from_xcl(path):
    src = open(path, encoding="utf-8").read()
    names = [m.group(1) for m in re.finditer(r'Encoding \{ name: "([A-Z0-9_]+)"', src)]
    out = []
    for m in re.finditer(r'Inst \{ name: "([A-Z0-9_]+)".*?encs: &\[(.*?)\] \},\n', src):
        for e in re.finditer(r"InstEnc \{ encoding: (\d+), opcode: (\d+)", m.group(2)):
            out.append((names[int(e.group(1))], int(e.group(2)), m.group(1)))
    return out


def main(src, dst):
    rows = from_xml(src) if src.endswith(".xml") else from_xcl(src)
    table = sorted({(ENC[e][0], op, n.lower(), ENC[e][1]) for e, op, n in rows if e in ENC})
    order = [v[0] for v in ENC.values()]
    table.sort(key=lambda r: (order.index(r[0]), r[1]))
    lines = [
        "// @generated by scripts/gen_isa_table.py -- do not edit by hand.",
        "// Source: AMD Machine-Readable GPU ISA Specification, AMD RDNA 2",
        "// (Copyright Advanced Micro Devices, Inc., MIT licence), via xcl's",
        "// generated rdna2_spec.rs (GPL-3.0-or-later). See THIRD_PARTY_NOTICES.md.",
        "//! Every RDNA2 (GFX10.3) instruction AMD's ISA defines: encoding, opcode",
        "//! number and mnemonic, for disassembly and per-opcode coverage reports.",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]",
        "pub enum Encoding {",
    ]
    seen = []
    for v in order:
        if v not in seen:
            seen.append(v)
            lines.append(f"    {v},")
    lines += [
        "}",
        "",
        "impl Encoding {",
        "    pub const ALL: &'static [Encoding] = &[",
    ]
    lines += [f"        Encoding::{v}," for v in seen]
    lines += [
        "    ];",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct OpcodeInfo {",
        "    pub encoding: Encoding,",
        "    pub opcode: u16,",
        "    pub mnemonic: &'static str,",
        "    /// Instruction size without a trailing literal / DPP / SDWA dword.",
        "    pub dwords: u8,",
        "}",
        "",
        f"/// All {len(table)} RDNA2 instructions (encoding, opcode) of AMD's ISA.",
        "pub const OPCODE_TABLE: &[OpcodeInfo] = &[",
    ]
    for enc, op, name, dw in table:
        lines.append(
            f'    OpcodeInfo {{ encoding: Encoding::{enc}, opcode: {op:#x}, mnemonic: "{name}", dwords: {dw} }},'
        )
    lines += [
        "];",
        "",
        "/// Number of entries in [`OPCODE_TABLE`].",
        "pub const fn opcode_count() -> usize {",
        "    OPCODE_TABLE.len()",
        "}",
        "",
        "/// Look up [`OpcodeInfo`] by `(encoding, opcode)`.",
        "pub fn lookup_opcode_info(encoding: Encoding, opcode: u16) -> Option<OpcodeInfo> {",
        "    OPCODE_TABLE",
        "        .iter()",
        "        .copied()",
        "        .find(|info| info.encoding == encoding && info.opcode == opcode)",
        "}",
        "",
        "/// Mnemonic for `(encoding, opcode)`.",
        "pub fn lookup_opcode(encoding: Encoding, opcode: u16) -> Option<&'static str> {",
        "    lookup_opcode_info(encoding, opcode).map(|info| info.mnemonic)",
        "}",
        "",
        "/// `(encoding, opcode)` for a mnemonic.",
        "pub fn find_mnemonic(mnemonic: &str) -> Option<OpcodeInfo> {",
        "    OPCODE_TABLE.iter().copied().find(|i| i.mnemonic == mnemonic)",
        "}",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "",
        "    #[test]",
        "    fn table_matches_amd_numbers() {",
        f"        assert_eq!(opcode_count(), {len(table)});",
        "        for &enc in Encoding::ALL {",
        "            assert!(OPCODE_TABLE.iter().any(|i| i.encoding == enc), \"{enc:?}\");",
        "        }",
        '        assert_eq!(lookup_opcode(Encoding::Mimg, 0xe7), Some("image_bvh64_intersect_ray"));',
        '        assert_eq!(lookup_opcode(Encoding::Vop3, 0x144), Some("v_cubeid_f32"));',
        '        assert_eq!(lookup_opcode(Encoding::Vop3, 0x176), Some("v_mad_u64_u32"));',
        '        assert_eq!(lookup_opcode(Encoding::Ds, 0xb3), Some("ds_bpermute_b32"));',
        '        assert_eq!(lookup_opcode(Encoding::Sop2, 0x26), Some("s_mul_i32"));',
        '        assert_eq!(lookup_opcode(Encoding::Sop1, 0x1f), Some("s_getpc_b64"));',
        '        assert_eq!(lookup_opcode(Encoding::FlatScratch, 0x0c), Some("scratch_load_dword"));',
        '        assert_eq!(lookup_opcode(Encoding::Vop3p, 0x0e), Some("v_pk_fma_f16"));',
        '        assert_eq!(find_mnemonic("v_mbcnt_lo_u32_b32").map(|i| i.opcode), Some(0x365));',
        "    }",
        "}",
        "",
    ]
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(table)} instructions to {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
